# ---------------------------------------------------------------- note names
BASE_NAMES = {'C': 0, 'D': 2, 'E': 4, 'F': 5, 'G': 7, 'A': 9, 'B': 11}

NOTE_RE = __import__('re').compile(r'^([A-Ga-g])([#b]?)-?(-?\d+)$')

def nn(s):
    """'A-4' / 'G#5' -> XM note number (C-5 == 61 == 523.25 Hz at rel.note 0)."""
    m = NOTE_RE.match(s)
    if not m:
        raise ValueError("bad note name: %r" % s)
    pc = BASE_NAMES[m.group(1).upper()]
    if m.group(2) == '#':
        pc += 1
    elif m.group(2) == 'b':
        pc -= 1
    return 1 + int(m.group(3)) * 12 + pc

def nn_name(n):
    names = ['C-', 'C#', 'D-', 'D#', 'E-', 'F-', 'F#', 'G-', 'G#', 'A-', 'A#', 'B-']
    return names[(n - 1) % 12] + str((n - 1) // 12)

