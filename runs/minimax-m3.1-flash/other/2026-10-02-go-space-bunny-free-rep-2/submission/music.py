def bass_bar(chord, pattern, octave=2):
    root, iv = CHORD[chord]
    base = nn(f"{root}-{octave}")
    out = []
    for step, deg in pattern:
        if deg < 0:
            out.append((step, None))
        elif deg == 0:
            out.append((step, base))
        elif deg == 1:
            out.append((step, base + 12))
        elif deg == 2:
            out.append((step, base + iv[2] if len(iv) > 2 else base + 7))
        elif deg == 3:
            out.append((step, base + iv[1]))
        elif deg == 4:
            out.append((step, base - 12))
    return out

