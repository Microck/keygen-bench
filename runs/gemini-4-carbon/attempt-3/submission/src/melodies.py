def write_lead_events(pat, ch, inst, events, echo_ch=None, echo_delay=6, echo_scale=0.36, max_echo_row=125):
    """
    events: list of tuples (row, dur, note, vol) or (row, dur, note, vol, mode)
      mode: None | ('glide', speed) | ('vib', spd, dep) | ('stac',)
    """
    sorted_evs = sorted(events, key=lambda x: x[0])
    next_starts = [ev[0] for ev in sorted_evs[1:]] + [128]

    for idx, ev in enumerate(sorted_evs):
        row, dur, nt, vol = ev[:4]
        mode = ev[4] if len(ev) > 4 else None
        nxt = next_starts[idx]
        end_r = min(row + dur, nxt, 128)

        if not (0 <= row < 128):
            continue

        if mode and mode[0] == 'glide' and idx > 0:
            gspd = mode[1]
            pat.set(row, ch, note=nt, inst=0, vol=VOL(vol), eff=TONE_PORTA(gspd))
            for gr in range(row + 1, min(row + 4, end_r)):
                pat.set(gr, ch, eff=TONE_PORTA(0))
        else:
            pat.set(row, ch, note=nt, inst=inst, vol=VOL(vol))

        # Add singing tail vibrato on sustained notes
        if dur >= 8 and (not mode or mode[0] != 'stac'):
            v_spd, v_dep = (mode[1], mode[2]) if (mode and mode[0] == 'vib') else (9, 4)
            for vr in range(row + 4, end_r - 1):
                pat.set(vr, ch, eff=VIBRATO(v_spd, v_dep))

        # Place clean OFF if note ends before next event
        if end_r < nxt and end_r < 128:
            pat.set(end_r, ch, note=OFF)

        # Stereo tap-echo on echo_ch (only for prominent notes, never spilling past max_echo_row)
        if echo_ch is not None and dur >= 2:
            er = row + echo_delay
            edur = min(dur, 8)
            if 0 <= er <= max_echo_row - 2:
                evol = max(10, int(round(vol * echo_scale)))
                pat.set(er, echo_ch, note=nt, inst=inst, vol=VOL(evol), eff=PANNING(224))
                e_off = min(er + edur, max_echo_row)
                # Only put OFF if another echo doesn't overwrite it first
                pat.set(e_off, echo_ch, note=OFF)


