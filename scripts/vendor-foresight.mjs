// Rebuild the checked-in browser asset from the exact versions in package-lock.json.
import { build } from "esbuild";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { join } from "node:path";

const root = fileURLToPath(new URL("../", import.meta.url));
const output = join(root, "web/classic/core/vendor");
await mkdir(output, { recursive: true });
const notices = [];
for (const name of ["js.foresight", "position-observer", "tabbable"]) {
  const directory = join(root, "node_modules", name);
  const { version } = JSON.parse(await readFile(join(directory, "package.json"), "utf8"));
  notices.push(`${name}@${version}\n\n${(await readFile(join(directory, "LICENSE"), "utf8")).trim()}`);
}
await build({
  stdin: { contents: 'export { ForesightManager } from "js.foresight";', resolveDir: root },
  bundle: true,
  format: "esm",
  platform: "browser",
  target: "es2022",
  minify: true,
  plugins: [{
    name: "position-observer-cleanup",
    setup(builder) {
      let patched = false;
      builder.onLoad({ filter: /position-observer\/dist\/index\.js$/ }, async ({ path }) => {
        const source = await readFile(path, "utf8");
        // position-observer 1.0.3 forgets these resources during individual cleanup.
        // Remove this patch when a pinned upstream release performs both operations.
        const before = "      this.#positionObservers.get(element)?.disconnect();\n      this.#visibilityObserver.unobserve(element);";
        if (source.split(before).length !== 2) throw new Error("position-observer cleanup patch no longer matches; review upstream");
        const after = "      this.#positionObservers.get(element)?.disconnect();\n      this.#positionObservers.delete(element);\n      this.#resizeObserver.unobserve(element);\n      this.#visibilityObserver.unobserve(element);";
        patched = true;
        return { contents: source.replace(before, after), loader: "js" };
      });
      builder.onEnd(() => {
        if (!patched) throw new Error("position-observer cleanup patch was not applied; review dependency entry points");
      });
    },
  }],
  legalComments: "inline",
  outfile: join(output, "foresight.js"),
  banner: { js: "// Generated by npm run vendor:foresight. See foresight-LICENSE.txt for upstream MIT licenses." },
});
await writeFile(join(output, "foresight-LICENSE.txt"), notices.join("\n\n---\n\n") + "\n");
